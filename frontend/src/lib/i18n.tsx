function getInitialLanguage(): Language {
  try {
    return localStorage.getItem('clubworms-language') === 'en' ? 'en' : 'uk'
  } catch {
    return 'uk'
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    document.title = language === 'uk'
      ? 'clubworms — книжкові та кіноклуби'
      : 'clubworms — clubs for shared interests'
    try {
      localStorage.setItem('clubworms-language', language)
    } catch {
      // Language selection remains available when storage is disabled.
    }
  }, [language])

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key) => messages[language][key],
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}
